/* ── RTF encoder ─────────────────────────────────────────────────────────── */
function toRtf(text) {
  let out = '';
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if      (ch === '\\') { out += '\\\\'; }
    else if (ch === '{')  { out += '\\{';  }
    else if (ch === '}')  { out += '\\}';  }
    else if (ch === '\r') { /* skip */     }
    else if (ch === '\n') { out += '\\par\n'; }
    else if (cp > 127)    { out += '\\u' + cp + '?'; }
    else                  { out += ch; }
  }
  return out;
}

/* ── Build RTF document ──────────────────────────────────────────────────── */
const body = toRtf(SOURCE);

