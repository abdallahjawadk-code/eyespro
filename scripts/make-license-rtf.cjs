  '{\\colortbl ;\\red11\\green30\\blue61;}\n' +
  '\\viewkind4\\pard\\rtlpar\\ql\\cf1\\f0\\fs18 ' +
  body +
  '}';

fs.writeFileSync(DST, rtf, 'ascii');
